export function computeReliefStats(
  sources: FoodSource[],
  requests: ReliefRequest[],
  missions: ReliefMission[]
): ReliefStats {
  const activeSources = sources.filter((s) => s.status === 'ACTIVE');
  const activeStatuses = new Set(['PENDING', 'ASSIGNED', 'ON_THE_WAY']);
  return {
    totalMealsAvailable: activeSources.reduce((sum, s) => sum + s.availableMeals, 0),
    totalWaterAvailable: activeSources.reduce((sum, s) => sum + s.waterBottles, 0),
    activeMissions: missions.filter((m) => activeStatuses.has(m.status) || m.status === 'ASSIGNED').length,
    completedMissions: missions.filter((m) => m.status === 'COMPLETED' || m.status === 'DELIVERED').length,
    pendingRequests: requests.filter((r) => r.status === 'PENDING').length,
    criticalShortages: sources.filter((s) => s.status === 'DEPLETED').length,
    activeFoodSources: activeSources.length,
    aiServiceStatus: 'FALLBACK_ACTIVE',
  };
}
